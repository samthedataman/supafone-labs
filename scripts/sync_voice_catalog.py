#!/usr/bin/env python3
"""Generate public, identical language snapshots from a reviewed catalog JSON.

The input is a public model catalog only. No backend modules or credentials are copied.
Usage: python scripts/sync_voice_catalog.py path/to/catalog.json
"""
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = json.loads(Path(sys.argv[1]).read_text())
if set(source) != {"version", "components"}:
    raise SystemExit("Expected a public model catalog (version and components only)")
allowed = {"id", "layer", "provider", "model", "canonical_model", "protocol", "status", "capabilities", "evidence", "docs_url"}
if any(set(item) - allowed for item in source["components"]):
    raise SystemExit("Unexpected component data; inspect input before publishing")
canonical = json.dumps(source, sort_keys=True, separators=(",", ":"))
manifest = {"registry_version": source["version"], "registry_hash": hashlib.sha256(canonical.encode()).hexdigest(), **source}
(root / "src/supafone_labs/voice_catalog.json").write_text(json.dumps(manifest, indent=2) + "\n")
(root / "sdk-ts/src/voice-catalog.ts").write_text(
    '// Generated by scripts/sync_voice_catalog.py. Live API remains authoritative.\n'
    + 'const snapshot = ' + json.dumps(manifest, indent=2) + ';\n'
    + 'export function voiceCatalogSnapshot(): typeof snapshot { return JSON.parse(JSON.stringify(snapshot)); }\n'
)
print(f"Generated {len(source['components'])} endpoints at {source['version']}")
